    echo '<!DOCTYPE html><html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1">';
    echo '<title>Setup complete</title>';
    echo '<style>body{font-family:system-ui,sans-serif;max-width:40rem;margin:2rem auto;padding:0 1rem;line-height:1.5}</style></head><body>';
    echo '<h1>Setup complete</h1>';
    echo '<p>This site is already set up. The installer is closed so it cannot be run again by mistake.</p>';
    echo '<p><a href="../user/login.php">Log in</a> · <a href="../index.php">Go to the site</a></p>';
    echo '<p style="font-size:0.9rem;color:#555">You can delete or rename the <code>install</code> folder for extra safety.</p>';
    echo '</body></html>';
    exit;
}

function install_load_pdo_from_config(string $configLocal): PDO {
    if (!is_file($configLocal)) {
        throw new RuntimeException('No config.local.php found.');
    }
    require $configLocal;
    if (!isset($pdo) || !($pdo instanceof PDO)) {
        throw new RuntimeException('Database connection not available.');
    }
    return $pdo;
}

// Probe write access inside this project folder only
$probeOk = false;
$probeError = '';
$probeFile = $root . '/.install_write_probe';
if (@file_put_contents($probeFile, 'ok') !== false) {
    $probeOk = true;
    @unlink($probeFile);
} else {
    $last = error_get_last();
    $probeError = $last['message'] ?? 'write failed';
}

// ---------- Lock / resume ----------
if (is_file($lockFile)) {
    install_show_complete_page();
}

if (is_file($configLocal) && $_SERVER['REQUEST_METHOD'] !== 'POST') {
    try {
        $pdo = install_load_pdo_from_config($configLocal);
        $userCount = (int) $pdo->query('SELECT COUNT(*) FROM users')->fetchColumn();
        if ($userCount > 0) {
            if (!is_dir($root . '/db')) {
                @mkdir($root . '/db', 0755, true);
            }
            if (!is_file($loaderDb)) {
                install_write_loader_db_php($loaderDb);
            }
            install_bootstrap_permissions($pdo);
            file_put_contents($lockFile, 'Installed ' . gmdate('c') . " (lock backfilled)\n");
            install_show_complete_page();
        }
        $_SESSION['install_db_ok'] = true;
        $step = 4;
        $message = 'Database is ready. Create your admin account to finish setup.';
    } catch (Throwable $e) {
        $error = 'Could not use existing config: ' . $e->getMessage();
    }
}

// ---------- POST ----------
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    try {
        if ($step === 2) {
            $step = 3;
        } elseif ($step === 3) {
            if (!$probeOk) {
                throw new RuntimeException(
                    'PHP cannot create files in this project folder. '
                    . ($probeError !== '' ? 'Detail: ' . $probeError : '')
                );
            }

            $host = trim($_POST['db_host'] ?? '127.0.0.1');
            $name = trim($_POST['db_name'] ?? '');
            $user = trim($_POST['db_user'] ?? '');
            $pass = $_POST['db_pass'] ?? '';

            if ($name === '' || $user === '') {
                throw new RuntimeException('Database name and database username are required.');
            }

            $dsn = "mysql:host={$host};dbname={$name};charset=utf8mb4";
            $pdo = new PDO($dsn, $user, $pass, [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
            ]);

            // Force MySQL session time zone to UTC (+00:00) during installation checks
            $pdo->exec("SET time_zone = '+00:00';");

            if (!install_db_is_empty($pdo)) {
                throw new RuntimeException(
                    'This database is not empty. Use a new empty database (or drop all tables) and try again.'
                );
            }

            install_write_config_local($configLocal, $host, $name, $user, $pass);
            install_write_loader_db_php($loaderDb);

            install_import_sql($pdo, $root . '/db/schema_baseline.sql');
            install_import_sql($pdo, $root . '/db/seed_baseline.sql');
            if (is_file($root . '/db/seed_permissions.sql')) {
                install_import_sql($pdo, $root . '/db/seed_permissions.sql');
            }
            if (is_file($root . '/db/seed_role_permissions.sql')) {
                install_import_sql($pdo, $root . '/db/seed_role_permissions.sql');
            }

            $functions = $root . '/includes/functions.php';
            if (is_file($functions)) {
                require_once $functions;
            }
            $latest = install_latest_schema_version($root . '/db/migrations');
            if (function_exists('set_schema_version')) {
                set_schema_version($pdo, $latest);
            } else {
                $stmt = $pdo->prepare(
                    "INSERT INTO site_settings (setting_key, setting_value) VALUES ('schema_version', ?)
                     ON DUPLICATE KEY UPDATE setting_value = ?"
                );
                $stmt->execute([(string) $latest, (string) $latest]);
            }

            $_SESSION['install_db_ok'] = true;
            $step = 4;
            $message = 'Database connected and schema imported. Create your admin account.';
        } elseif ($step === 4) {
            if (empty($_SESSION['install_db_ok']) || !is_file($configLocal)) {
                throw new RuntimeException('Complete the database step first.');
            }

            $pdo = install_load_pdo_from_config($configLocal);

            $username = trim($_POST['admin_username'] ?? '');
            $email    = trim($_POST['admin_email'] ?? '');
            $password = $_POST['admin_password'] ?? '';
            $confirm  = $_POST['admin_password_confirm'] ?? '';

            if ($username === '' || $email === '' || $password === '') {
                throw new RuntimeException('All admin fields are required.');
            }
            if (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
                throw new RuntimeException('Invalid email address.');
            }
            if (strlen($password) < 8) {
                throw new RuntimeException('Password must be at least 8 characters.');
            }
            if ($password !== $confirm) {
                throw new RuntimeException('Passwords do not match.');
            }

            $hash = password_hash($password, PASSWORD_DEFAULT);
            $roleId = 1;

            try {
                // Set is_new_user = 1 so the admin goes through onboarding wizard on first login
                $stmt = $pdo->prepare("
                    INSERT INTO users (username, email, password_hash, role_id, email_verified, is_active, is_new_user)
                    VALUES (?, ?, ?, ?, 1, 1, 1)
                ");
                $stmt->execute([$username, $email, $hash, $roleId]);
            } catch (PDOException $e) {
                $stmt = $pdo->prepare("
                    INSERT INTO users (username, email, password_hash, role_id)
                    VALUES (?, ?, ?, ?)
                ");
                $stmt->execute([$username, $email, $hash, $roleId]);
            }

            $check = $pdo->prepare('SELECT COUNT(*) FROM users WHERE username = ?');
            $check->execute([$username]);
            if ((int) $check->fetchColumn() < 1) {
                throw new RuntimeException('Admin user was not saved. Check the users table structure.');
            }

            install_bootstrap_permissions($pdo);

            if (!is_file($loaderDb)) {
                install_write_loader_db_php($loaderDb);
            }

            if (!is_dir($root . '/db')) {
                @mkdir($root . '/db', 0755, true);
            }
            file_put_contents($lockFile, 'Installed ' . gmdate('c') . "\n");
            unset($_SESSION['install_db_ok']);
            $step = 5;
            $message = 'Installation complete.';
        }
    } catch (Throwable $e) {
        $error = $e->getMessage();
        if ($step === 3 && is_file($configLocal) && empty($_SESSION['install_db_ok'])) {
            @unlink($configLocal);
        }
        if ($step === 4) {
            $step = 4;
            $_SESSION['install_db_ok'] = true;
        }
    }
}

