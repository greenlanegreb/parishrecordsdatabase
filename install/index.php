function install_db_is_empty(PDO $pdo): bool {
    $tables = $pdo->query('SHOW TABLES')->fetchAll(PDO::FETCH_COLUMN);
    return count($tables) === 0;
}

function install_import_sql(PDO $pdo, string $path): void {
    if (!is_file($path)) {
        throw new RuntimeException("Missing SQL file: {$path}");
    }
    $sql = file_get_contents($path);
    $sql = preg_replace('/\/\*![0-9]{5}.*?\*\//s', '', $sql);
    $sql = preg_replace('/^--.*$/m', '', $sql);
    $sql = preg_replace('/^\/\*M!.*$/m', '', $sql);
    $statements = array_filter(array_map('trim', explode(';', $sql)));

    $pdo->exec('SET FOREIGN_KEY_CHECKS=0');
    try {
        foreach ($statements as $statement) {
            if ($statement === '') {
                continue;
            }
            if (preg_match('/^(SET|USE)\s+/i', $statement)) {
                continue;
            }
            $pdo->exec($statement);
        }
    } finally {
        $pdo->exec('SET FOREIGN_KEY_CHECKS=1');
    }
}

function install_latest_schema_version(string $migrationsDir): int {
    $latest = 0;
    if (is_dir($migrationsDir)) {
        foreach (glob($migrationsDir . '/*.php') as $file) {
            if (preg_match('/(\d+)_/', basename($file), $m)) {
                $latest = max($latest, (int) $m[1]);
            }
        }
    }
    return max(1, $latest);
}

function install_write_config_local(string $path, string $host, string $db, string $user, string $pass): void {
    $hostE = var_export($host, true);
    $dbE   = var_export($db, true);
    $userE = var_export($user, true);
    $passE = var_export($pass, true);

    $content = <<<PHP
<?php
// config.local.php - Generated by installer. Do not commit. This project folder only.
if (!defined('BASE_PATH')) {
    \$doc_root = rtrim(str_replace('\\\\', '/', \$_SERVER['DOCUMENT_ROOT'] ?? ''), '/');
    \$project_root = rtrim(str_replace('\\\\', '/', dirname(__FILE__)), '/');
    \$base_path = str_replace(\$doc_root, '', \$project_root);
    define('BASE_PATH', \$base_path);
}

\$host = {$hostE};
\$db = {$dbE};
\$user = {$userE};
\$pass = {$passE};
\$charset = 'utf8mb4';

\$dsn = "mysql:host=\$host;dbname=\$db;charset=\$charset";
\$options = [
    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
    PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    PDO::ATTR_EMULATE_PREPARES => false,
];

\$log_dir = __DIR__ . '/logs';
if (!is_dir(\$log_dir)) {
    @mkdir(\$log_dir, 0755, true);
}

try {
    \$pdo = new PDO(\$dsn, \$user, \$pass, \$options);

    // Force MySQL session time zone to UTC (+00:00) to prevent the 1-hour drift
    \$pdo->exec("SET time_zone = '+00:00';");

    if (is_file(__DIR__ . '/db/maintenance_guard.php')) {
        require_once __DIR__ . '/db/maintenance_guard.php';
        if (function_exists('check_maintenance_mode')) {
            check_maintenance_mode(\$pdo);
        }
    }
} catch (PDOException \$e) {
    throw new PDOException('Database Connection Failed: ' . \$e->getMessage(), (int) \$e->getCode());
}

PHP;

    $result = @file_put_contents($path, $content);
    if ($result === false) {
        $last = error_get_last();
        $detail = $last['message'] ?? 'unknown error';
        throw new RuntimeException(
            'Could not write config.local.php (' . $path . '). PHP said: ' . $detail
        );
    }
}

function install_write_loader_db_php(string $path): void {
    $content = <<<'PHP'
<?php
// db/db.php - Generated by installer (loader only). Secrets live in config.local.php.
$projectRoot = dirname(__DIR__);
$configLocal = $projectRoot . '/config.local.php';

if (is_file($configLocal)) {
    require $configLocal;
    return;
}

$script = str_replace('\\', '/', $_SERVER['SCRIPT_NAME'] ?? '');
if (strpos($script, '/install/') !== false || str_ends_with($script, '/install')) {
    return;
}

$base = str_replace('\\', '/', dirname($script));
if (preg_match('#/(user|admin|api|actions|db|partials|includes)(/|$)#', $base)) {
    $base = dirname($base);
}
$base = rtrim($base, '/');
header('Location: ' . $base . '/install/');
exit;

PHP;

    $dir = dirname($path);
    if (!is_dir($dir)) {
        if (!@mkdir($dir, 0755, true) && !is_dir($dir)) {
            throw new RuntimeException('Could not create db/ directory.');
        }
    }
    if (@file_put_contents($path, $content) === false) {
        $last = error_get_last();
        throw new RuntimeException(
            'Could not write db/db.php loader. PHP said: ' . ($last['message'] ?? 'unknown')
        );
    }
}

function install_bootstrap_permissions(PDO $pdo): void {
    $core_permissions = [
        ['manage_settings', 'Manage global site settings, mail drivers, and maintenance mode'],
        ['manage_users', 'Manage user accounts'],
        ['invite_users', 'Create and invite new users'],
        ['manage_tables', 'Manage dynamic database tables and column schema definitions'],
        ['manage_columns', 'Configure table columns'],
        ['edit_records', 'Add, edit, and transcribe records into the system'],
        ['access_data_entry', 'Allows accessing the core data entry workstation and creating records'],
        ['view_public', 'View and search records'],
        ['view_leaderboard', 'Allows viewing community contribution leaderboards'],
        ['manage_feedback', 'Manage feedback'],
        ['submit_feedback', 'Allows submitting public feedback and inquiries'],
        ['manage_volunteers', 'Manage volunteers'],
        ['submit_volunteer', 'Allows submitting volunteer interest and transcription applications'],
        ['moderate_suggestions', 'Approve, reject, or override user edit suggestions'],
        ['manage_moderation', 'Manage and review user correction suggestions and moderation queues'],
        ['moderate_submissions', 'Review and moderate pending user submissions'],
        ['access_profile', 'Allows viewing and managing personal user profile and security settings'],
        ['access_onboarding', 'Allows accessing the first-time user onboarding setup wizard'],
    ];

    $insPerm = $pdo->prepare(
        'INSERT IGNORE INTO permissions (permission_key, description) VALUES (?, ?)'
    );
    foreach ($core_permissions as [$key, $desc]) {
        $insPerm->execute([$key, $desc]);
    }

    $pdo->exec("
        INSERT IGNORE INTO role_permissions (role_id, permission_id)
        SELECT 1, id FROM permissions
    ");

    $pdo->exec("
        INSERT IGNORE INTO role_permissions (role_id, permission_id)
        SELECT 4, id FROM permissions WHERE permission_key = 'view_public'
    ");
}

