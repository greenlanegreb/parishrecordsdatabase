function install_db_is_empty(PDO $pdo): bool {
    $stmt = $pdo->query('SHOW TABLES');
    $tables = $stmt !== false ? $stmt->fetchAll(PDO::FETCH_COLUMN) : [];
    return is_array($tables) && count($tables) === 0;
}

function install_import_sql(PDO $pdo, string $path): void {
    if (!is_file($path)) {
        throw new RuntimeException("Missing SQL file: {$path}");
    }
    $sql = file_get_contents($path);
    if ($sql === false) {
        throw new RuntimeException("Could not read SQL file: {$path}");
    }
    $sql = preg_replace('/\/\*![0-9]{5}.*?\*\//s', '', $sql);
    $sql = preg_replace('/^--.*$/m', '', $sql);
    $sql = preg_replace('/^\/\*M!.*$/m', '', $sql);
    $statements = is_string($sql) ? array_filter(array_map('trim', explode(';', $sql))) : [];

    $pdo->exec('SET FOREIGN_KEY_CHECKS=0');
    try {
        foreach ($statements as $statement) {
            if ($statement === '') {
                continue;
            }
            if (preg_match('/^(SET|USE)\s+/i', $statement)) {
                continue;
            }
            $pdo->exec($statement);
        }
    } finally {
        $pdo->exec('SET FOREIGN_KEY_CHECKS=1');
    }
}

function install_run_migrations(PDO $pdo, string $migrationsDir): void {
    if (!is_dir($migrationsDir)) {
        return;
    }

    $files = glob($migrationsDir . '/*.php');
    if ($files === false || empty($files)) {
        return;
    }

    $migrations = [];
    foreach ($files as $file) {
        $basename = basename($file);
        // Extract the leading numbers before any dash or underscore
        if (preg_match('/^(\d+)[-_]/', $basename, $m)) {
            $num = (int)$m[1];
            $migrations[$num] = $file;
        }
    }

    // Sort numerically so 002 comes before 026 and 100
    ksort($migrations, SORT_NUMERIC);

    foreach ($migrations as $num => $file) {
        $basename = basename($file);
        try {
            // Include the migration file. 
            // Depending on how your migrations are written, including them executes them or defines functions.
            include_once $file;
            if (function_exists('up')) {
                up($pdo);
            }
        } catch (\Throwable $e) {
            throw new RuntimeException("Migration failed [{$basename}]: " . $e->getMessage(), 0, $e);
        }
    }
}

function install_latest_schema_version(string $migrationsDir): int {
    $latest = 0;
    if (is_dir($migrationsDir)) {
        $globFiles = glob($migrationsDir . '/*.php');
        if ($globFiles !== false) {
            foreach ($globFiles as $file) {
                $m = [];
                if (preg_match('/(\d+)_/', basename($file), $m)) {
                    $latest = max($latest, (int)$m[1]);
                }
            }
        }
    }
    return max(1, $latest);
}

function install_write_config_local(string $path, string $host, string $db, string $user, string $pass): void {
